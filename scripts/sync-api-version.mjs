#!/usr/bin/env node
/* =============================================================================
   Writes lib/api-version.js: the fingerprint of the two server-side engines the edge answers
   for (lib/prompts.js, lib/sizing.js).
   -----------------------------------------------------------------------------
   WHY (2026-09-30). The room asks the Cloudflare Worker for /size and /prompt first (CLAUDE.md
   §2.15), and the Worker runs whatever copy of those modules was last deployed with
   `wrangler deploy`. A module changed without a redeploy made the edge and the origin answer
   differently - measured that day: the deployed Worker still said "top" on every back view where
   main's engine says "shirt". So the Worker stamps every answer with THIS fingerprint
   (X-Pear-Api), the build stamps the room with it (PEAR_API_VERSION), and the room takes an edge
   answer only when the two agree - otherwise it asks its own origin, which always runs the code it
   was built with. A redeploy makes the edge fast again; it can never make it wrong.
   Usage:  npm run sync:api-version            (writes the file)
           node scripts/sync-api-version.mjs --check   (exit 1 if stale)
   test/api-version.test.mjs fails the suite when the committed value is stale.
   ============================================================================= */
import { readFileSync, writeFileSync } from "node:fs";
import { createHash } from "node:crypto";
import { pathToFileURL } from "node:url";

const SOURCES = ["../lib/prompts.js", "../lib/sizing.js"].map((p) => new URL(p, import.meta.url));
const OUT = new URL("../lib/api-version.js", import.meta.url);

export function apiFingerprint(texts = SOURCES.map((u) => readFileSync(u, "utf8"))) {
  const h = createHash("sha256");
  for (const t of texts) h.update(t.replace(/\r\n/g, "\n")).update("\u0000");
  return h.digest("hex").slice(0, 16);
}

export function renderApiVersion(fp = apiFingerprint()) {
  return `/* GENERATED by scripts/sync-api-version.mjs - do not edit by hand (npm run sync:api-version).
   The fingerprint of lib/prompts.js + lib/sizing.js. The Worker sends it with every /size and
   /prompt answer (X-Pear-Api) and the room accepts an edge answer only when it matches the one it
   was built with - see the script's header. */
export const API_VERSION = "${fp}";
`;
}

const isMain = !!process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  const want = renderApiVersion();
  if (process.argv.includes("--check")) {
    let cur = "";
    try { cur = readFileSync(OUT, "utf8").replace(/\r\n/g, "\n"); } catch { /* missing */ }
    if (cur !== want) { console.error("✗ lib/api-version.js is stale - run: npm run sync:api-version"); process.exit(1); }
    console.log("✓ lib/api-version.js matches lib/prompts.js + lib/sizing.js");
  } else {
    writeFileSync(OUT, want);
    console.log(`✓ wrote lib/api-version.js (${apiFingerprint()})`);
  }
}
